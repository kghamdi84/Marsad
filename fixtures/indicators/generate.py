"""Golden values for the indicator tests.

Inputs: a seeded synthetic OHLCV series (so the file is reproducible).
Expected outputs: pandas, an implementation independent of packages/core.

Conventions (documented in packages/core/src/indicators.ts):
- EMA is seeded with the SMA of the first `period` values (TA-Lib and StockCharts convention).
- RSI and ATR use Wilder smoothing, seeded with the simple average of the first `period` values.
- True range of the first bar is high minus low.
Run: python3 fixtures/indicators/generate.py
"""
import json
import numpy as np
import pandas as pd

rng = np.random.default_rng(20261123)
n = 120
close = 100 * np.exp(np.cumsum(rng.normal(0.0004, 0.012, n)))
open_ = np.concatenate([[100.0], close[:-1]]) * np.exp(rng.normal(0, 0.003, n))
high = np.maximum(open_, close) * (1 + np.abs(rng.normal(0, 0.004, n)))
low = np.minimum(open_, close) * (1 - np.abs(rng.normal(0, 0.004, n)))
volume = rng.integers(500_000, 5_000_000, n).astype(float)

df = pd.DataFrame({"o": open_, "h": high, "l": low, "c": close, "v": volume})


def seeded_ewm(s, first, period, alpha):
    """Seed = mean of s[first:first+period], then the recursion y = alpha*x + (1-alpha)*y_prev."""
    out = pd.Series(np.nan, index=s.index)
    seed_idx = first + period - 1
    if seed_idx >= len(s):
        return out
    seed = s.iloc[first:first + period].mean()
    tail = s.iloc[seed_idx + 1:]
    x = pd.concat([pd.Series([seed]), tail]).reset_index(drop=True)
    e = x.ewm(alpha=alpha, adjust=False).mean()
    out.iloc[seed_idx:] = e.values
    return out


def sma(s, p):
    return s.rolling(p).mean()


def ema(s, p):
    return seeded_ewm(s, 0, p, 2 / (p + 1))


def rsi(c, p=14):
    d = c.diff()
    gain = d.clip(lower=0)
    loss = -d.clip(upper=0)
    ag = seeded_ewm(gain, 1, p, 1 / p)
    al = seeded_ewm(loss, 1, p, 1 / p)
    return 100 - 100 / (1 + ag / al)


def atr(h, l, c, p=14):
    pc = c.shift(1)
    tr = pd.concat([h - l, (h - pc).abs(), (l - pc).abs()], axis=1).max(axis=1)
    return tr, seeded_ewm(tr, 0, p, 1 / p)


def macd(c, fast=12, slow=26, sig=9):
    line = ema(c, fast) - ema(c, slow)
    signal = seeded_ewm(line, slow - 1, sig, 2 / (sig + 1))
    return line, signal, line - signal


def vwap(h, l, c, v):
    tp = (h + l + c) / 3
    return (tp * v).cumsum() / v.cumsum()


def rvol(v, p=20):
    return v / v.shift(1).rolling(p).mean()


def clean(s):
    return [None if pd.isna(x) else float(x) for x in s]


tr, atr14 = atr(df.h, df.l, df.c, 14)
m_line, m_sig, m_hist = macd(df.c)
golden = {
    "_note": "Generated by fixtures/indicators/generate.py. Inputs are synthetic and seeded; expected values are from pandas.",
    "input": {k: [float(x) for x in df[k]] for k in ["o", "h", "l", "c", "v"]},
    "sma20": clean(sma(df.c, 20)),
    "ema12": clean(ema(df.c, 12)),
    "ema26": clean(ema(df.c, 26)),
    "rsi14": clean(rsi(df.c, 14)),
    "trueRange": clean(tr),
    "atr14": clean(atr14),
    "macd": {"line": clean(m_line), "signal": clean(m_sig), "histogram": clean(m_hist)},
    "vwap": clean(vwap(df.h, df.l, df.c, df.v)),
    "rvol20": clean(rvol(df.v, 20)),
}
with open("fixtures/indicators/golden.json", "w") as f:
    json.dump(golden, f)
print("wrote golden.json; last rsi", golden["rsi14"][-1], "last macd hist", golden["macd"]["histogram"][-1])
